import 'dotenv/config';
import express from 'express';
import session from 'express-session';
import cors from 'cors';

import { GoogleSpreadsheet } from 'google-spreadsheet';
import { JWT, OAuth2Client } from 'google-auth-library';


const app = express();
const PORT = process.env.PORT || 3001;
const SPREADSHEET_ID = process.env.SPREADSHEET_ID;
const isProduction = process.env.NODE_ENV === 'production';

if (isProduction) {
  app.set('trust proxy', 1);
}

const allowedOrigins = ['http://localhost:5173', 'https://threejsdemo.onrender.com']

app.use(cors({ origin: allowedOrigins, credentials:true }));
app.use(express.json());

app.use(session({
  secret: process.env.SESSION_SECRET,
  resave: false,
  saveUninitialized: false,
  cookie: {
    httpOnly: true,
    sameSite: isProduction ? 'none' : 'lax',    
    secure: isProduction,
    maxAge: 1000 * 60 * 60 * 24,
  },
}));

// auth functions

const oauthClient = new OAuth2Client(process.env.GOOGLE_CLIENT_ID);

function hasSessionUser(req) {
  return Boolean(req.session && req.session.user);
}

function ensureAuth(req, res, next) {
  if (hasSessionUser(req)) {
    return next();
  }
  return res.status(401).json({ error: 'Unauthorized' });
}


// spreadsheet functions
const serviceAccountAuth = new JWT({
  // env var values here are copied from service account credentials generated by google
  // see "Authentication" section in docs for more info
  email: process.env.GOOGLE_SERVICE_ACCOUNT,
  key: process.env.GOOGLE_PRIVATE_KEY,
  scopes: ['https://www.googleapis.com/auth/spreadsheets'],
});

let cachedData = null;

async function fetchSpreadsheetData(forceRefresh = false) {
  if (cachedData && !forceRefresh) {
    return cachedData;
  }

  const doc = new GoogleSpreadsheet(SPREADSHEET_ID, serviceAccountAuth);
  await doc.loadInfo(); // Loads document properties and worksheets
  console.log(`Loaded document: ${doc.title}`);

  const sheet = doc.sheetsByIndex[0];
  const rows = await sheet.getRows();

  cachedData = {
    title: doc.title,
    sheet: sheet.title,
    table: rows.map((row) => row.toObject()),
  };

  return cachedData;
}

// Auth API endpoints

app.post('/auth/google/token', async (req, res) => {
  try {
    const { credential } = req.body;
    if (!credential) {
      return res.status(400).json({ error: 'Missing credential' });
    }

    const ticket = await oauthClient.verifyIdToken({
      idToken: credential,
      audience: process.env.GOOGLE_CLIENT_ID,
    });

    const payload = ticket.getPayload();
    if (!payload || !payload.sub) {
      return res.status(401).json({ error: 'Invalid token payload' });
    }

    req.session.regenerate((err) => {
      if (err) {
        return res.status(500).json({ error: 'Session error' });
      }

      req.session.user = {
        id: payload.sub,
        name: payload.name || '',
        email: payload.email || '',
        picture: payload.picture || '',
      };

      return res.json({ ok: true, user: req.session.user });
    });
  } catch {
    return res.status(401).json({ error: 'Invalid Google credential' });
  }
});

app.post('/auth/logout', (req, res) => {
  if (!req.session) {
    return res.json({ ok: true });
  }
  req.session.destroy(() => {
    res.clearCookie('connect.sid');
    return res.json({ ok: true });
  });
});

app.get('/auth/me', (req, res) => {
  if (req.session && req.session.user) {
    return res.json({ authenticated: true, user: req.session.user });
  }
  return res.status(401).json({ authenticated: false });
});


// Sheets API endpoint
app.get('/api/sheet-data', ensureAuth, async (req, res) => {
  try {
    const forceRefresh = req.query.refresh === '1';
    const data = await fetchSpreadsheetData(forceRefresh);
    res.json(data);
  } catch (error) {
    console.error('Error reading spreadsheet:', error);
    res.status(500).json({ error: 'Failed to read spreadsheet data' });
  }
});

app.listen(PORT, () => {
  console.log(`Backend API server running at http://localhost:${PORT}`);
});

